def t(locale: str, key: str, **fmt: Any) -> str:
    """按语种取文案模板并格式化；缺失回退默认语种，再缺失返回 key。

    - 所有 ``%`` / ``{...}`` 占位一律用 ``str.format``（模板里不要裸花括号）
    - 调用方只需传最具体语种（normalize 已在上游完成）；这里做防御性回退
    """
    table = MESSAGES.get(locale) or MESSAGES.get(DEFAULT_LOCALE) or {}
    template = table.get(key)
    if template is None and locale != DEFAULT_LOCALE:
        template = (MESSAGES.get(DEFAULT_LOCALE) or {}).get(key)
    if template is None:
        return key
    if not fmt:
        return template
    try:
        return template.format(**fmt)
    except (KeyError, ValueError, IndexError):
        return template


def translate(locale: str, key: str, **fmt: Any) -> str:
    """t 的别名（语义更明确：把 key 翻译成指定语种文案）。"""
    return t(locale, key, **fmt)


